  let currentLang = 'ko';

  // navigator.language prefix → supported language (first match wins, so zh-TW precedes zh)
  const BROWSER_LANG_PREFIXES = [
    [['zh-tw', 'zh-hk'], 'zh-TW'], [['zh'], 'zh-CN'], [['tl', 'fil'], 'tl'],
    ...['ja', 'vi', 'th', 'id', 'ru', 'mn', 'uz', 'ne', 'my', 'km', 'es', 'fr', 'de', 'ar', 'hi', 'pt', 'bn', 'en'].map((l) => [[l], l])
  ];

  function getStoredLang() {
    try {
      const saved = localStorage.getItem('kdam_lang');
      if (saved && TRANSLATIONS[saved]) return saved;
    } catch (e) {}
    const browserLang = (navigator.language || '').toLowerCase();
    const match = BROWSER_LANG_PREFIXES.find(([prefixes]) => prefixes.some((p) => browserLang.startsWith(p)));
    return match ? match[1] : 'ko';
  }

  function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'ko';
    currentLang = lang;
    try {
      localStorage.setItem('kdam_lang', lang);
    } catch (e) {}
    document.documentElement.setAttribute('lang', lang);
    applyTranslations();
  }

  // Registry values (js/registry.js BASINS / DAM_TYPES) → translation keys; one map for tabs, filters and table
  const BASIN_KEYS = { '한강': 'basinHan', '낙동강': 'basinNakdong', '금강': 'basinGeum', '영산·섬진강': 'basinYeongsan' };
  const DAM_TYPE_KEYS = { '다목적댐': 'multiPurpose', '용수전용댐': 'waterSupply', '홍수조절용': 'floodControl' };
  const basin = (name) => (BASIN_KEYS[name] ? t(BASIN_KEYS[name]) : name);
  const damType = (type) => (DAM_TYPE_KEYS[type] ? t(DAM_TYPE_KEYS[type]) : type);

  function t(key, params = {}) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS['ko'];
    let text = dict[key] || TRANSLATIONS['ko'][key] || key;
    Object.keys(params).forEach(p => {
      text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
    });
    return text;
  }

  function applyTranslations() {
    // 1. Page Title & Intro
    const titleEl = document.querySelector('.page-intro h1');
    const subEl = document.querySelector('.page-intro p');
    if (titleEl) titleEl.textContent = t('title');
    if (subEl) subEl.textContent = t('subtitle');

    // 2. Search Input placeholder
    const searchInput = document.getElementById('search-input');
    if (searchInput) searchInput.setAttribute('placeholder', t('searchPlaceholder'));

    // 3. Stats card labels
    const cardLabels = document.querySelectorAll('.stat-card-label');
    if (cardLabels.length >= 4) {
      cardLabels[0].textContent = t('avgRate');
      cardLabels[1].textContent = t('totalStorage');
      cardLabels[2].textContent = t('totalInflow');
      cardLabels[3].textContent = t('totalOutflow');
    }

    // 4. Filter Selects
    const selType = document.getElementById('select-dam-type');
    if (selType && selType.options.length >= 4) {
      selType.options[0].textContent = t('allTypes');
      selType.options[1].textContent = t('multiPurpose');
      selType.options[2].textContent = t('waterSupply');
      selType.options[3].textContent = t('floodControl');
    }

    const selStatus = document.getElementById('select-status-filter');
    if (selStatus && selStatus.options.length >= 4) {
      selStatus.options[0].textContent = t('allStatus');
      selStatus.options[1].textContent = t('statusDischarge');
      selStatus.options[2].textContent = t('statusDrought');
      selStatus.options[3].textContent = t('statusNormal');
    }

    // 5. Basin Tabs
    document.querySelectorAll('.tab-btn').forEach(tab => {
      const name = tab.getAttribute('data-basin');
      const labelEl = tab.querySelector('.tab-label') || tab;
      labelEl.textContent = name === 'ALL' ? t('basinAll') : basin(name);
    });

    // 6. Table Headers
    const thMap = {
      'name': 'thName',
      'basin': 'thBasin',
      'type': 'thType',
      'storageRate': 'thRate',
      'diffNormalYear': 'thDiff',
      'waterLevel': 'thLevel',
      'storageVolume': 'thStorage',
      'inflow': 'thInflow',
      'outflow': 'thOutflow'
    };
    document.querySelectorAll('#dams-table thead th').forEach((th, idx) => {
      const sortField = th.getAttribute('data-sort');
      if (sortField && thMap[sortField]) {
        th.childNodes[0].textContent = t(thMap[sortField]);
      } else if (idx === 4) {
        th.textContent = t('thStatus');
      }
    });

    // Trigger re-render of table so type badges and numbers update localized if needed
    if (global.appReRenderTable) {
      global.appReRenderTable();
    }
  }

