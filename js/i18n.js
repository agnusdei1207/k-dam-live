  let currentLang = 'ko';

  function getStoredLang() {
    try {
      const saved = localStorage.getItem('kdam_lang');
      if (saved && TRANSLATIONS[saved]) return saved;
      const browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
      if (browserLang.startsWith('zh-tw') || browserLang.startsWith('zh-hk')) return 'zh-TW';
      if (browserLang.startsWith('zh')) return 'zh-CN';
      if (browserLang.startsWith('ja')) return 'ja';
      if (browserLang.startsWith('vi')) return 'vi';
      if (browserLang.startsWith('th')) return 'th';
      if (browserLang.startsWith('tl') || browserLang.startsWith('fil')) return 'tl';
      if (browserLang.startsWith('id')) return 'id';
      if (browserLang.startsWith('ru')) return 'ru';
      if (browserLang.startsWith('mn')) return 'mn';
      if (browserLang.startsWith('uz')) return 'uz';
      if (browserLang.startsWith('ne')) return 'ne';
      if (browserLang.startsWith('my')) return 'my';
      if (browserLang.startsWith('km')) return 'km';
      if (browserLang.startsWith('es')) return 'es';
      if (browserLang.startsWith('fr')) return 'fr';
      if (browserLang.startsWith('de')) return 'de';
      if (browserLang.startsWith('ar')) return 'ar';
      if (browserLang.startsWith('hi')) return 'hi';
      if (browserLang.startsWith('pt')) return 'pt';
      if (browserLang.startsWith('bn')) return 'bn';
      if (browserLang.startsWith('en')) return 'en';
    } catch (e) {
      console.warn('Failed to detect browser language', e);
    }
    return 'ko';
  }

  function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'ko';
    currentLang = lang;
    try {
      localStorage.setItem('kdam_lang', lang);
    } catch (e) {}
    document.documentElement.setAttribute('lang', lang);
    applyTranslations();
  }

  function t(key, params = {}) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS['ko'];
    let text = dict[key] || TRANSLATIONS['ko'][key] || key;
    Object.keys(params).forEach(p => {
      text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
    });
    return text;
  }

  function applyTranslations() {
    // 1. Page Title & Intro
    const titleEl = document.querySelector('.page-intro h1');
    const subEl = document.querySelector('.page-intro p');
    if (titleEl) titleEl.textContent = t('title');
    if (subEl) subEl.textContent = t('subtitle');

    // 2. Search Input placeholder
    const searchInput = document.getElementById('search-input');
    if (searchInput) searchInput.setAttribute('placeholder', t('searchPlaceholder'));

    // 3. Stats card labels
    const cardLabels = document.querySelectorAll('.stat-card-label');
    if (cardLabels.length >= 4) {
      cardLabels[0].textContent = t('avgRate');
      cardLabels[1].textContent = t('totalStorage');
      cardLabels[2].textContent = t('totalInflow');
      cardLabels[3].textContent = t('totalOutflow');
    }

    // 4. Filter Selects
    const selType = document.getElementById('select-dam-type');
    if (selType && selType.options.length >= 4) {
      selType.options[0].textContent = t('allTypes');
      selType.options[1].textContent = t('multiPurpose');
      selType.options[2].textContent = t('waterSupply');
      selType.options[3].textContent = t('floodControl');
    }

    const selStatus = document.getElementById('select-status-filter');
    if (selStatus && selStatus.options.length >= 4) {
      selStatus.options[0].textContent = t('allStatus');
      selStatus.options[1].textContent = t('statusNormal');
      selStatus.options[2].textContent = t('statusDischarge');
      selStatus.options[3].textContent = t('statusDrought');
    }

    // 5. Basin Tabs
    const basinTabs = document.querySelectorAll('.tab-btn');
    basinTabs.forEach(tab => {
      const basin = tab.getAttribute('data-basin');
      if (basin === 'all') tab.textContent = t('basinAll');
      else if (basin === '한강') tab.textContent = t('basinHan');
      else if (basin === '낙동강') tab.textContent = t('basinNakdong');
      else if (basin === '금강') tab.textContent = t('basinGeum');
      else if (basin === '영산강·섬진강') tab.textContent = t('basinYeongsan');
    });

    // 6. Table Headers
    const thMap = {
      'name': 'thName',
      'basin': 'thBasin',
      'type': 'thType',
      'storageRate': 'thRate',
      'diffPrevYear': 'thDiff',
      'waterLevel': 'thLevel',
      'storageVolume': 'thStorage',
      'inflow': 'thInflow',
      'outflow': 'thOutflow'
    };
    document.querySelectorAll('#dams-table thead th').forEach((th, idx) => {
      const sortField = th.getAttribute('data-sort');
      if (sortField && thMap[sortField]) {
        th.childNodes[0].textContent = t(thMap[sortField]);
      } else if (idx === 4) {
        th.textContent = t('thStatus');
      }
    });

    // Trigger re-render of table so type badges and numbers update localized if needed
    if (global.appReRenderTable) {
      global.appReRenderTable();
    }
  }

